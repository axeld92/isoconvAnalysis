const PROJECT_ROOT = normpath(joinpath(@__DIR__, ".."))
const DEFAULT_REPORT = joinpath(PROJECT_ROOT, "docs", "deconvolution_audit.md")
const DEFAULT_MACHINE_REPORT = joinpath(
    PROJECT_ROOT, "docs", "audits", "m5_deconvolution_results.toml"
