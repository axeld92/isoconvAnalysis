function selected_colors()
    return Makie.wong_colors()
end

function write_representative_figure(path, processed, comparison)
    result = candidate_result(comparison, comparison.selected_model)
    experiment_by_id = Dict(experiment.source_id => experiment for experiment in processed)
    figure = Figure(; size=(1000, 760))
    axis_rate = Axis(
        figure[1, 1];
        xlabel="Conversion, alpha",
        ylabel="dalpha/dt (min⁻¹)",
        title="Representative M6 fit — 50% waste tire",
        yscale=log10,
    )
    axis_residual = Axis(
        figure[2, 1]; xlabel="Conversion, alpha", ylabel="Log-rate residual"
    )
    colors = selected_colors()
    for (color_index, experiment_id) in enumerate(result.experiment_ids)
        indices = findall(==(experiment_id), result.point_experiment_ids)
        rate = heating_rate(experiment_by_id[experiment_id])
        scatter!(
            axis_rate,
            result.alpha[indices],
            result.observed_rate_per_min[indices];
            color=(colors[color_index], 0.45),
            markersize=4,
            label="$rate K/min observed",
        )
        lines!(
            axis_rate,
            result.alpha[indices],
            result.fitted_rate_per_min[indices];
            color=colors[color_index],
            linewidth=2,
            label="$rate K/min fitted",
        )
        lines!(
            axis_residual,
            result.alpha[indices],
            result.log_rate_residual[indices];
            color=colors[color_index],
            linewidth=1.5,
        )
    end
    hlines!(axis_residual, [0.0]; color=:gray45, linestyle=:dash)
    axislegend(axis_rate; position=:rb, nbanks=2)
    save(path, figure)
    return path
end

function write_model_selection_figure(path, comparisons, config)
    compositions = [0, 25, 50, 75, 100]
    models = config.reaction_models.models
    deltas = [
        min(comparisons[composition].criterion_deltas[index], 100.0) for
        composition in compositions, index in eachindex(models)
    ]
    figure = Figure(; size=(1200, 560))
    axis = Axis(
        figure[1, 1];
        xticks=(eachindex(models), string.(models)),
        yticks=(eachindex(compositions), string.(compositions)),
        xlabel="Reaction-model candidate",
        ylabel="Waste-tire dry-mass fraction (%)",
        title="M6 BIC deltas (capped at 100)",
        xticklabelrotation=pi / 3,
    )
    heatmap_plot = heatmap!(
        axis, eachindex(models), eachindex(compositions), transpose(deltas)
    )
    Colorbar(figure[1, 2], heatmap_plot; label="Delta BIC")
    save(path, figure)
    return path
end

function write_compensation_figure(path, processed, compensation)
    experiment = only(filter(value -> value.source_id == "dynamic_wt050_rate10", processed))
    result = compensation[experiment.source_id]
    minimum_energy, maximum_energy = extrema(result.model_activation_energies_kJ_per_mol)
    energy_line = collect(range(minimum_energy, maximum_energy; length=200))
    log_a_line = @. result.regression.intercept + result.regression.slope * energy_line
    figure = Figure(; size=(800, 560))
    axis = Axis(
        figure[1, 1];
        xlabel="Single-rate fitted E (kJ/mol)",
        ylabel="Single-rate fitted ln(A/min⁻¹)",
        title="Compensation diagnostic — 50% waste tire, 10 K/min",
    )
    scatter!(
        axis,
        result.model_activation_energies_kJ_per_mol,
        result.model_log_preexponentials_per_min;
        color=:black,
        markersize=9,
        label="Fixed-model pairs",
    )
    lines!(axis, energy_line, log_a_line; color=:steelblue, linewidth=2, label="OLS line")
    scatter!(
        axis,
        [result.reference_activation_energy_kJ_per_mol],
        [result.estimated_log_preexponential_per_min];
        color=:orangered,
        marker=:star5,
        markersize=18,
        label="Starink-reference evaluation",
    )
    axislegend(axis; position=:rb)
    save(path, figure)
    return path
end

function main()
    config, processed, _, comparisons, reference_energies, compensation = run_audit()
    mkpath(dirname(DEFAULT_REPORT))
    mkpath(dirname(DEFAULT_MACHINE_REPORT))
    mkpath(DEFAULT_FIGURE_DIRECTORY)
    write_markdown(
        DEFAULT_REPORT, config, processed, comparisons, reference_energies, compensation
    )
    write_machine_report(
        DEFAULT_MACHINE_REPORT,
        config,
        processed,
        comparisons,
        reference_energies,
        compensation,
    )
    write_representative_figure(
        joinpath(DEFAULT_FIGURE_DIRECTORY, "representative_kinetic_fit.svg"),
        processed,
        comparisons[50],
    )
    write_model_selection_figure(
        joinpath(DEFAULT_FIGURE_DIRECTORY, "model_selection.svg"), comparisons, config
    )
    write_compensation_figure(
        joinpath(DEFAULT_FIGURE_DIRECTORY, "compensation_diagnostic.svg"),
        processed,
        compensation,
    )
    println("Wrote docs/reaction_model_audit.md")
    println("Wrote docs/audits/m6_reaction_model_results.toml")
    return println("Wrote docs/figures/m6/")
end

main()
