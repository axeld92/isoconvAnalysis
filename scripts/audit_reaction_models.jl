composition_percent(experiment) = round(Int, 100 * experiment.composition.waste_tire)
function heating_rate(experiment)
    return round(Int, experiment.diagnostics.measured_heating_rate_K_per_min)
end

function candidate_result(comparison::KineticModelComparison, model::Symbol)
    return only(filter(result -> result.model.name == model, comparison.results))
end

function parameter_value(result::KineticTripletResult, name::Symbol)
    index = findfirst(parameter -> parameter.name == name, result.parameters)
    return isnothing(index) ? NaN : result.parameters[index].estimate
end

function format_number(value; digits=3)
    return isfinite(value) ? @sprintf("%.*f", digits, value) : "not available"
end

function format_scientific(value)
    return isfinite(value) ? @sprintf("%.3e", value) : "not available"
end

function count_values(values)
    return join(
        ["`$value` × $(count(==(value), values))" for value in sort(unique(values))], ", "
    )
end

function run_audit()
    config = load_config(joinpath(PROJECT_ROOT, "config", "analysis_defaults.toml"))
    catalog = load_dataset_catalog(joinpath(PROJECT_ROOT, "config", "datasets.toml"))
    raw = load_experiments(catalog; roles=[:calibration])
    processed = preprocess.(raw, Ref(config))
    groups = Dict(
        composition => sort(
            filter(experiment -> composition_percent(experiment) == composition, processed);
            by=experiment -> experiment.source_id,
        ) for composition in (0, 25, 50, 75, 100)
    )
    comparisons = Dict(
        composition => compare_reaction_models(group, config) for
        (composition, group) in groups
    )
    reference_energies = Dict{Int,Float64}()
    for (composition, group) in groups
        starink = analyze(:starink, group, config)
        reference_energies[composition] = median(
            Float64.(collect(skipmissing(starink.activation_energy_kJ_per_mol)))
        )
    end
    compensation = Dict{String,CompensationResult}()
    for experiment in processed
        composition = composition_percent(experiment)
        compensation[experiment.source_id] = analyze_compensation(
            experiment, reference_energies[composition], config
        )
    end
    return config, processed, groups, comparisons, reference_energies, compensation
end

