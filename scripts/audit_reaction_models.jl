toml_string(value) = "\"" * replace(String(value), "\\" => "\\\\", "\"" => "\\\"") * "\""
toml_float(value) =
    if isnan(value)
        "nan"
    elseif value == Inf
        "inf"
    elseif value == -Inf
        "-inf"
    else
        @sprintf("%.16g", value)
    end
toml_float_array(values) = "[" * join(toml_float.(values), ", ") * "]"
toml_string_array(values) = "[" * join(toml_string.(values), ", ") * "]"
toml_bool_array(values) = "[" * join(string.(values), ", ") * "]"

